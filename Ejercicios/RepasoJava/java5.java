public class java5 {
    public static void main(String[] args) {
       System.out.println("OPERADORES DE COMPARACION:");
        int a = 10;
        int b = 20;

        System.out.println("a > b: " + (a > b));
        System.out.println("a <= b: " + (a < b));
        System.out.println("a == b: " + (a == b));
        System.out.println("a != b: " + (a != b));
        System.out.println("(a <= b) && (a > 0): " + ((a < b) && (a > 0)));   
        System.out.println("(a > b) || (b > 0): " + ((a > b) || (b > 0)));     

        
    }
    
}
